-- WordOrbit v1 schema: the six tables from docs/PLAN.md ("Data model").
--
-- Shared content (anyone may read, only the seed may write):
--   words, word_pairs, questions
-- Per-user data (row-level security: each user sees and writes only their own rows):
--   user_word_state, answers, user_traps
--
-- Written for Supabase: auth.users and auth.uid() come from Supabase Auth.
-- Writes to the content tables happen through the seed (service role), which
-- bypasses row-level security, so those tables have read policies only.

create extension if not exists vector;

-- ---------------------------------------------------------------- content

create table public.words (
  id          bigint generated by default as identity primary key,
  word        text not null unique check (word = lower(word) and word ~ '^[a-z]+$'),
  pos         text not null check (pos in ('noun', 'verb', 'adjective', 'adverb')),
  definition  text not null,
  examples    text[] not null check (cardinality(examples) between 2 and 3),
  difficulty  smallint not null check (difficulty between 1 and 3),
  source      text not null,
  -- 3D position in the galaxy, scaled to the cube from -1 to 1 (pipeline/layout.py)
  x           real not null,
  y           real not null,
  z           real not null,
  -- all-mpnet-base-v2 embedding, unit length (pipeline/embed.py, DECISIONS.md entry 11)
  embedding   vector(768) not null
);

create table public.word_pairs (
  id             bigint generated by default as identity primary key,
  word_a_id      bigint not null references public.words (id) on delete cascade,
  word_b_id      bigint not null references public.words (id) on delete cascade,
  type           text not null check (type in ('look-alike', 'near-synonym')),
  spelling_score real,
  sound_score    real,
  meaning_score  real,
  explanation    text,
  check (word_a_id <> word_b_id)
);
-- A pair is stored once per type, whichever word comes first.
create unique index word_pairs_unique_pair
  on public.word_pairs (least(word_a_id, word_b_id), greatest(word_a_id, word_b_id), type);
create index word_pairs_word_b on public.word_pairs (word_b_id);

create table public.questions (
  id              bigint generated by default as identity primary key,
  target_word_id  bigint not null references public.words (id) on delete cascade,
  kind            text not null check (kind in ('sentence_completion', 'definition_match')),
  prompt          text not null,            -- a sentence with ___, or a definition
  options         text[] not null check (cardinality(options) between 2 and 6),
  explanation     text,
  source          text not null check (source in ('hand', 'ai')),
  checks          jsonb not null default '{}'::jsonb,   -- results of the three automatic checks (v2)
  created_at      timestamptz not null default now()
);
create index questions_target on public.questions (target_word_id);

-- ---------------------------------------------------------------- per user

create table public.user_word_state (
  user_id         uuid not null references auth.users (id) on delete cascade,
  word_id         bigint not null references public.words (id) on delete cascade,
  -- FSRS card fields, as ts-fsrs names them
  due             timestamptz not null default now(),
  stability       real not null default 0,
  difficulty      real not null default 0,
  elapsed_days    integer not null default 0,
  scheduled_days  integer not null default 0,
  learning_steps  integer not null default 0,
  reps            integer not null default 0,
  lapses          integer not null default 0,
  fsrs_state      smallint not null default 0 check (fsrs_state between 0 and 3),  -- new, learning, review, relearning
  last_review     timestamptz,
  status          text not null default 'new' check (status in ('new', 'learning', 'mastered')),
  primary key (user_id, word_id)
);
create index user_word_state_due on public.user_word_state (user_id, due);

-- Every answer ever given. The training data for the v2 confusion model and the
-- source of every metric, so users may add rows but never change or delete them.
create table public.answers (
  id               bigint generated by default as identity primary key,
  user_id          uuid not null default auth.uid() references auth.users (id) on delete cascade,
  question_id      bigint references public.questions (id) on delete set null,
  chosen_word_id   bigint not null references public.words (id),
  correct_word_id  bigint not null references public.words (id),
  is_correct       boolean not null generated always as (chosen_word_id = correct_word_id) stored,
  response_ms      integer check (response_ms >= 0),
  answered_at      timestamptz not null default now()
);
create index answers_user_time on public.answers (user_id, answered_at);

create table public.user_traps (
  user_id          uuid not null references auth.users (id) on delete cascade,
  picked_word_id   bigint not null references public.words (id) on delete cascade,
  correct_word_id  bigint not null references public.words (id) on delete cascade,
  misses           integer not null default 0 check (misses >= 0),
  last_missed      timestamptz,
  risk_score       real not null default 0,
  primary key (user_id, picked_word_id, correct_word_id),
  check (picked_word_id <> correct_word_id)
);

-- ---------------------------------------------------------------- row-level security

alter table public.words           enable row level security;
alter table public.word_pairs      enable row level security;
alter table public.questions       enable row level security;
alter table public.user_word_state enable row level security;
alter table public.answers         enable row level security;
alter table public.user_traps      enable row level security;

-- Content: readable by everyone, including signed-out visitors browsing the galaxy.
create policy "words are public"      on public.words      for select to anon, authenticated using (true);
create policy "word pairs are public" on public.word_pairs for select to anon, authenticated using (true);
create policy "questions are public"  on public.questions  for select to anon, authenticated using (true);

-- Per-user tables: signed-in users only, and only their own rows.
-- (select auth.uid()) is evaluated once per query instead of once per row.
create policy "own review state" on public.user_word_state for all to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

create policy "read own answers" on public.answers for select to authenticated
  using (user_id = (select auth.uid()));
create policy "add own answers"  on public.answers for insert to authenticated
  with check (user_id = (select auth.uid()));
-- No update or delete policy on answers: the log is append-only for users.

create policy "own traps" on public.user_traps for all to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
