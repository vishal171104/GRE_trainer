"""Step 5 of the offline pipeline: write the database seed file.

Usage:  python pipeline/build_seed.py [--model mpnet]

Reads the word list and the pipeline output and writes supabase/seed.sql,
which loads the shared content into the tables created by
supabase/migrations/0001_initial_schema.sql:

  words       every word with its definition, examples, 3D position and embedding
  word_pairs  only the trap candidates marked y/yes in the `accept` column of
              pipeline/output/trap_candidates.csv (the hand-curated list)

The seed upserts: running it again updates rows in place and never deletes
anything, so it is safe on a database that already has users' answers.
"""

import argparse
import csv
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
WORDS_PATH = ROOT / "data" / "words.json"
OUTPUT_DIR = ROOT / "pipeline" / "output"
SEED_PATH = ROOT / "supabase" / "seed.sql"
EMBEDDING_DIM = 768  # must match vector(768) in the migration
YES = {"y", "yes"}
NO = {"n", "no"}


def sql_text(value: str) -> str:
    """A SQL string literal: single quotes doubled."""
    return "'" + value.replace("'", "''") + "'"


def sql_text_array(values: list[str]) -> str:
    return "ARRAY[" + ", ".join(sql_text(v) for v in values) + "]::text[]"


def sql_vector(vector: np.ndarray) -> str:
    """A pgvector literal such as '[0.0123,-0.4]'. Nine significant digits keep float32 exact."""
    if not np.isfinite(vector).all():
        raise ValueError("embedding contains NaN or infinite values")
    return "'[" + ",".join(f"{float(v):.9g}" for v in vector) + "]'"


def sql_real(value) -> str:
    return "NULL" if value is None or value == "" else repr(float(value))


def accepted_pairs(csv_path: Path) -> list[dict]:
    """Rows of the trap candidate CSV that the reviewer accepted.

    `accept` may be y/yes (kept), n/no or blank (skipped); anything else is an error,
    so a typo cannot silently drop or add a pair.
    """
    if not csv_path.exists():
        return []
    kept = []
    with csv_path.open(newline="", encoding="utf-8") as handle:
        for line, row in enumerate(csv.DictReader(handle), start=2):
            mark = (row.get("accept") or "").strip().lower()
            if mark in YES:
                kept.append(row)
            elif mark and mark not in NO:
                raise ValueError(f"{csv_path.name} line {line}: accept must be y, n or blank, not {mark!r}")
    return kept


def word_id(word: str) -> str:
    return f"(SELECT id FROM public.words WHERE word = {sql_text(word)})"


def build_seed_sql(words: list[dict], positions: dict[str, dict], vectors: np.ndarray, pairs: list[dict]) -> str:
    """The whole seed file as text. `vectors` rows follow the order of `words`."""
    if vectors.shape != (len(words), EMBEDDING_DIM):
        raise ValueError(f"expected embeddings of shape ({len(words)}, {EMBEDDING_DIM}), got {vectors.shape}")
    missing = [w["word"] for w in words if w["word"] not in positions]
    if missing:
        raise ValueError(f"no 3D position for: {', '.join(missing[:5])}")
    known = {w["word"] for w in words}
    for pair in pairs:
        for side in ("word_a", "word_b"):
            if pair[side] not in known:
                raise ValueError(f"trap pair uses unknown word {pair[side]!r}")

    lines = [
        "-- Generated by pipeline/build_seed.py. Do not edit by hand; re-run the script.",
        "-- Upserts only: safe to run again, never deletes rows.",
        "BEGIN;",
        "",
        "INSERT INTO public.words (word, pos, definition, examples, difficulty, source, x, y, z, embedding) VALUES",
    ]
    rows = []
    for entry, vector in zip(words, vectors):
        p = positions[entry["word"]]
        rows.append(
            "  ("
            + ", ".join(
                [
                    sql_text(entry["word"]),
                    sql_text(entry["pos"]),
                    sql_text(entry["definition"]),
                    sql_text_array(entry["examples"]),
                    str(int(entry["difficulty"])),
                    sql_text(entry["source"]),
                    sql_real(p["x"]),
                    sql_real(p["y"]),
                    sql_real(p["z"]),
                    sql_vector(vector),
                ]
            )
            + ")"
        )
    lines.append(",\n".join(rows))
    lines.append(
        "ON CONFLICT (word) DO UPDATE SET pos = EXCLUDED.pos, definition = EXCLUDED.definition, "
        "examples = EXCLUDED.examples, difficulty = EXCLUDED.difficulty, source = EXCLUDED.source, "
        "x = EXCLUDED.x, y = EXCLUDED.y, z = EXCLUDED.z, embedding = EXCLUDED.embedding;"
    )

    if pairs:
        lines += ["", "INSERT INTO public.word_pairs (word_a_id, word_b_id, type, spelling_score, sound_score, meaning_score) VALUES"]
        lines.append(
            ",\n".join(
                f"  ({word_id(p['word_a'])}, {word_id(p['word_b'])}, 'look-alike', "
                f"{sql_real(p['spelling'])}, {sql_real(p['sound'])}, {sql_real(p['meaning'])})"
                for p in pairs
            )
        )
        lines.append(
            "ON CONFLICT (least(word_a_id, word_b_id), greatest(word_a_id, word_b_id), type) DO UPDATE SET "
            "spelling_score = EXCLUDED.spelling_score, sound_score = EXCLUDED.sound_score, "
            "meaning_score = EXCLUDED.meaning_score;"
        )
    lines += ["", "COMMIT;", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Write supabase/seed.sql from the pipeline output.")
    parser.add_argument("--model", default="mpnet")
    args = parser.parse_args()

    words = json.loads(WORDS_PATH.read_text(encoding="utf-8"))
    needed = [OUTPUT_DIR / "word_order.json", OUTPUT_DIR / "positions.json", OUTPUT_DIR / f"embeddings_{args.model}.npy"]
    absent = [p.name for p in needed if not p.exists()]
    if absent:
        print(f"Missing {', '.join(absent)} in pipeline/output. Run embed.py and layout.py first.")
        return 1
    order = json.loads(needed[0].read_text(encoding="utf-8"))
    if order != [w["word"] for w in words]:
        print("word_order.json does not match data/words.json. Re-run: python pipeline/embed.py")
        return 1

    positions = {p["word"]: p for p in json.loads(needed[1].read_text(encoding="utf-8"))}
    vectors = np.load(needed[2])
    try:
        pairs = accepted_pairs(OUTPUT_DIR / "trap_candidates.csv")
        sql = build_seed_sql(words, positions, vectors, pairs)
    except ValueError as error:
        print(f"Cannot build the seed: {error}")
        return 1

    SEED_PATH.parent.mkdir(parents=True, exist_ok=True)
    SEED_PATH.write_text(sql, encoding="utf-8")
    print(f"Wrote {SEED_PATH.relative_to(ROOT)}: {len(words)} words, {len(pairs)} accepted trap pairs.")
    if not pairs:
        print("No trap pairs yet: mark y in the accept column of pipeline/output/trap_candidates.csv.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
